PROJECT_FONTS = Path(__file__).resolve().parent.parent / "fonts"
FONT_DIRS = [p for p in (PROJECT_FONTS, Path(os.environ.get("PROXY_FONT_DIR", "")) if os.environ.get("PROXY_FONT_DIR") else None, Path(r"C:\Windows\Fonts")) if p]
# Magic prints names and the type line in Beleren (bold) and rules text in MPlantin; if those are not in fonts/, Calisto MT (a Plantin-style face that ships with Office) stands in.
DEFAULT_FONTS = {"title": ["beleren.ttf", "CALISTB.TTF", "constanb.ttf", "georgiab.ttf", "arialbd.ttf"],
                 "body": ["mplantin.ttf", "CALIST.TTF", "constan.ttf", "georgia.ttf", "arial.ttf"],
                 "italic": ["mplantin-italic.ttf", "CALISTI.TTF", "constani.ttf", "georgiai.ttf", "ariali.ttf"],
                 "bold": ["CALISTB.TTF", "arialbd.ttf"]}
FOOTER = "PROXY  |  art generated by AI  |  not for sale"

# frame, plate (name / type), box (rules text), accent
PALETTE = {"W": ("#d9cfae", "#f4efdc", "#faf7ea", "#e9dfb5"), "U": ("#2f6aa0", "#c7dcec", "#e4edf5", "#6aa6d6"), "B": ("#3a3335", "#c8c0be", "#dfd9d7", "#8a7d80"),
           "R": ("#b3412e", "#eccfc4", "#f5e5de", "#e0795f"), "G": ("#2d7548", "#cfe3ca", "#e4efdf", "#6bb887"), "M": ("#b99a45", "#ecdfae", "#f6efd3", "#e3c565"),
           "A": ("#8a929b", "#dadfe3", "#eceff1", "#b6bec6"), "L": ("#8a6f4d", "#e4dac6", "#f0eadc", "#b99b6d"), "C": ("#9aa0a6", "#e1e3e6", "#eff0f2", "#bfc4c9")}
# the colours Magic's own symbols are printed in (the Mana font project's, which match the cards)
DISC = {"w": "#f8e7b9", "u": "#b3ceea", "b": "#a69f9d", "r": "#eb9f82", "g": "#c4d3ca", "c": "#cac5c0", "2": "#cac5c0", "s": "#cac5c0"}


@dataclass
class Theme:
    colors: list[str]
    frame: str
    plate: str
    box: str
    accent: str
    frame2: str | None = None            # a two-colour card's frame fades from `frame` to `frame2`


def theme_for(unit: dict) -> Theme:
    t = unit.get("type_line", "")
    colors = [c for c in (unit.get("colors") or []) if c in PALETTE]
    if "Land" in t:
        key = "L"
    elif not colors:
        key = "A" if "Artifact" in t else "C"
    elif len(colors) == 1:
        key = colors[0]
    else:
        key = "M"
    f, p, b, a = PALETTE[key]
    f2 = PALETTE[colors[1]][0] if len(colors) == 2 else None
    if f2:
        f = PALETTE[colors[0]][0]
        a = PALETTE[colors[0]][3]
    return Theme(colors=colors, frame=f, plate=p, box=b, accent=a, frame2=f2)


def mix(c1: str, c2: str, t: float) -> str:
    a = [int(c1[i:i + 2], 16) for i in (1, 3, 5)]
    b = [int(c2[i:i + 2], 16) for i in (1, 3, 5)]
    return "#%02x%02x%02x" % tuple(int(x + (y - x) * t) for x, y in zip(a, b))


# ---------------------------------------------------------------------------------------------------------------------------------------------------------- templates

def template_dirs() -> list[Path]:
    return [BUILTIN, config.DATA / "templates"]


def list_templates() -> list[dict]:
    out = []
    for d in template_dirs():
        if d.is_dir():
            for p in sorted(d.glob("*.json")):
                try:
                    t = json.loads(p.read_text(encoding="utf-8"))
                    t.setdefault("id", p.stem)
                    out.append(t)
                except Exception:
                    continue
    return out


def stamp() -> float:
    """When the drawing code or any template last changed: cards drawn before this are out of date and get drawn again the next time they are asked for."""
    files = [Path(__file__).resolve()] + [p for d in template_dirs() if d.is_dir() for p in d.glob("*.json")]
    files += [p for p in (PROJECT_FONTS / "mana.ttf", PROJECT_FONTS / "beleren.ttf", PROJECT_FONTS / "mplantin.ttf") if p.is_file()]
    return max(p.stat().st_mtime for p in files)


def get_template(tid: str) -> dict:
    t = next((t for t in list_templates() if t["id"] == tid), None)
    if t is None:
        raise KeyError(f"no template {tid!r}")
    return t


def art_shape(tpl: dict) -> str:
    """Which picture shape to ask the model for, from the template's art window."""
    _, _, w, h = tpl["art_box"]
    r = w / h
    return "landscape" if r > 1.15 else "portrait" if r < 0.87 else "square"


# ------------------------------------------------------------------------------------------------------------------------------------------------------------- fonts

def _find_font(fams: tuple[str, ...]) -> Path | None:
    for fam in fams:
        for d in FONT_DIRS:
            if not d.is_dir():
                continue
            p = d / fam
            if p.is_file():
                return p
            low = fam.lower()
            hit = next((q for q in d.iterdir() if q.name.lower() == low), None) if d == PROJECT_FONTS else None
            if hit:
                return hit
    return None


@lru_cache(maxsize=256)
def _font(kind: str, size: int, families: tuple[str, ...]) -> ImageFont.FreeTypeFont:
    p = _find_font(families)
    return ImageFont.truetype(str(p), size) if p else ImageFont.load_default(size)


def font(tpl: dict, kind: str, size: int):
    fams = tuple((tpl.get("fonts") or {}).get(kind) or DEFAULT_FONTS[kind])
    return _font(kind, max(6, int(size)), fams)


@lru_cache(maxsize=1)
def _glyphs() -> dict[str, str]:
    try:
        return json.loads((PROJECT_FONTS / "mana-glyphs.json").read_text(encoding="utf-8"))
    except Exception:
        return {}


@lru_cache(maxsize=32)
def _mana_font(size: int):
    p = PROJECT_FONTS / "mana.ttf"
    return ImageFont.truetype(str(p), size) if p.is_file() else None


def _glyph_char(name: str) -> str | None:
    cp = _glyphs().get(name)
    return chr(int(cp, 16)) if cp else None


# ------------------------------------------------------------------------------------------------------------------------------------------------------------ symbols

def _symbol_key(sym: str) -> str:
    """'W/U' -> 'wu', '2/W' -> '2w', 'W/P' -> 'wp', 'T' -> 'tap', 'Q' -> 'untap', '10' -> '10'."""
    s = sym.lower()
    return {"t": "tap", "q": "untap", "∞": "infinity"}.get(s, s.replace("/", ""))


def _ink_glyph(layer: Image.Image, ch: str, size: int, cx: float, cy: float, fill: int = 255) -> None:
    """Draw the symbol-font character `ch` on an L-mode layer with its visible ink centred at (cx, cy)."""
    f = _mana_font(size)
    d = ImageDraw.Draw(layer)
    x0, y0, x1, y1 = d.textbbox((0, 0), ch, font=f)
    d.text((cx - (x0 + x1) / 2, cy - (y0 + y1) / 2), ch, font=f, fill=fill)


def pip(img: Image.Image, tpl: dict, sym: str, x: float, y: float, dia: float, shadow: bool = False) -> None:
    """One mana or other symbol the way Magic prints it: a coloured disc with the symbol's black icon (and a small drop shadow on the cost), top-left at (x, y)."""
    S = 4
    D = max(8, int(dia * S))
    pad = int(D * 0.1)
    tile = Image.new("RGBA", (D + 2 * pad, D + 2 * pad), (0, 0, 0, 0))
    t = ImageDraw.Draw(tile)
    box = (pad, pad, pad + D, pad + D)
    key = _symbol_key(sym)
    letters = re.sub(r"[^a-z0-9]", "", key)
    ink_layer = Image.new("L", tile.size, 0)

    if shadow:
        t.ellipse((pad - D * 0.07, pad + D * 0.07, pad + D - D * 0.07, pad + D + D * 0.07), fill=(0, 0, 0, 215))

    split = len(letters) in (2, 3) and letters[0] in "wubrgc2" and letters[1] in "wubrgc" and not letters.endswith("p") or (len(letters) == 3 and letters.endswith("p") and letters[0] in "wubrg" and letters[1] in "wubrg")
    phyrexian = letters.endswith("p") and letters[:1] in "wubrg" and len(letters) == 2
    if key in ("tap", "untap"):
        t.ellipse(box, fill="#171717")
    elif split:
        c1, c2 = letters[0], letters[1]
        t.pieslice(box, 90, 270, fill=DISC.get(c1, DISC["c"]))
        t.pieslice(box, 270, 90, fill=DISC.get(c2, DISC["c"]))
    elif phyrexian:
        t.ellipse(box, fill=DISC[letters[0]])
    else:
        t.ellipse(box, fill=DISC.get(key, DISC["c"]) if key in DISC else DISC["c"])

    # the icon(s)
    if _mana_font(10) is not None:
        if split:
            for half, (name, cx) in enumerate(((letters[0], 0.3), (letters[1], 0.7))):
                ch = _glyph_char(name)
                if ch:
                    part = Image.new("L", tile.size, 0)
                    _ink_glyph(part, ch, int(D * 0.5), pad + D * cx, pad + D * 0.5)
                    ink_layer = ImageChops.lighter(ink_layer, part)
        else:
            ch = _glyph_char(key)
            if ch:
                _ink_glyph(ink_layer, ch, int(D * 0.74), pad + D / 2, pad + D / 2)
    ink_col = (245, 245, 245, 255) if key in ("tap", "untap") else (20, 20, 20, 255)
    tile.paste(Image.new("RGBA", tile.size, ink_col), (0, 0), ink_layer)
    if ink_layer.getbbox() is None:                                  # no icon font or no such symbol: the letters themselves
        f = font(tpl, "bold", D * 0.56)
        ImageDraw.Draw(tile).text((pad + D / 2, pad + D / 2 + D * 0.03), sym[:2], font=f, fill=ink_col, anchor="mm")
    t.ellipse(box, outline=(25, 25, 25, 255), width=max(1, int(D / 24)))
    small = tile.resize((tile.width // S, tile.height // S), Image.LANCZOS)
    img.paste(small, (int(x - pad / S), int(y - pad / S)), small)


def cost_symbols(cost: str) -> list[str]:
    return re.findall(r"\{([^}]+)\}", cost or "")


def draw_cost(img, tpl, cost: str, right: float, y: float, dia: float, shadow: bool = True) -> float:
    """The mana cost, right-aligned at `right`. Returns the left edge it reached."""
    syms = cost_symbols(cost)
    gap = dia * 0.08
    x = right - len(syms) * (dia + gap) + gap
    for s in syms:
        pip(img, tpl, s, x, y, dia, shadow)
        x += dia + gap
    return right - len(syms) * (dia + gap) + gap


# ------------------------------------------------------------------------------------------------------------------------------------------------------------- text

def fit_line(tpl: dict, text: str, kind: str, max_w: float, size: int, min_size: int = 14):
    """The largest font (down to min_size) in which `text` fits one line; shortened with an ellipsis if even that does not."""
    for s in range(int(size), int(min_size) - 1, -1):
        f = font(tpl, kind, s)
        if f.getlength(text) <= max_w:
            return f, text
    f = font(tpl, kind, min_size)
    while text and f.getlength(text + "…") > max_w:
        text = text[:-1]
    return f, text + "…"


def _chunks(text: str):
    """Rules text as a list of paragraphs; each is a list of unbreakable chunks (a word, or glued words and symbols such as '{T},'), each a list of ('w'|'s', text) parts."""
    paras = []
    for para in text.split("\n"):
        chunks = []
        for word in para.split():
            parts = [("s", m[1:-1]) if m.startswith("{") else ("w", m) for m in re.findall(r"\{[^}]+\}|[^{]+", word)]
            chunks.append(parts)
        paras.append(chunks)
    return paras


def layout_text(tpl: dict, paras: list[tuple[str, bool]], max_w: float, size: int):
    """Wrap (text, italic_whole_paragraph) paragraphs into lines at font `size`. Returns (lines, total_height); a line is (items, para_start)."""
    f_body, f_it = font(tpl, "body", size), font(tpl, "italic", size)
    dia = size * 0.86
    space = f_body.getlength(" ")
    lines = []
    lh = size * 1.2
    for text, whole_italic in paras:
        for chunks in _chunks(text):
            first = True
            cur, cur_w = [], 0.0
            paren = False
            if not chunks:
                continue
            for chunk in chunks:
                flat = "".join(t for k, t in chunk if k == "w")
                it = whole_italic or paren or flat.startswith("(")
                if flat.startswith("("):
                    paren = True
                if ")" in flat:
                    paren = False
                f = f_it if it else f_body
                items, w = [], 0.0
                for k, t in chunk:
                    wd = dia + 1 if k == "s" else f.getlength(t)
                    items.append((k, t, it, wd))
                    w += wd
                add = w + (space if cur else 0)
                if cur and cur_w + add > max_w:
                    lines.append((cur, first))
                    first = False
                    cur, cur_w = [], 0.0
                    add = w
                cur.append(items)
                cur_w += add
            lines.append((cur, first))
    height = len(lines) * lh + sum(size * 0.4 for n, (_, start) in enumerate(lines) if start and n > 0)
    return lines, height


def draw_lines(img, d, tpl, lines, x: float, y: float, size: int, fill, shadow: bool) -> None:
    f_body, f_it = font(tpl, "body", size), font(tpl, "italic", size)
    space = f_body.getlength(" ")
    dia = size * 0.86
    lh = size * 1.2
    cy = y
    for n, (chunks, para_start) in enumerate(lines):
        if para_start and n > 0:
            cy += size * 0.4
        base = cy + size * 0.95
        cx = x
        for ci, chunk in enumerate(chunks):
            if ci:
                cx += space
            for k, t, it, wd in chunk:
                if k == "s":
                    pip(img, tpl, t, cx + 1, base - dia * 0.82, dia, True)
                else:
                    f = f_it if it else f_body
                    if shadow:
                        d.text((cx + 1.5, base + 1.5), t, font=f, fill=(0, 0, 0, 200), anchor="ls")
                    d.text((cx, base), t, font=f, fill=fill, anchor="ls")
                cx += wd
        cy += lh


def draw_body(img, d, tpl: dict, unit: dict, fill, shadow: bool) -> None:
    x, y, w, h = tpl["text_box"]
    pad = tpl.get("text_pad", 18)
    iw, ih = w - 2 * pad, h - 2 * pad
    oracle = (unit.get("oracle_text") or "").strip()
    flavor = (unit.get("flavor_text") or "").strip() if tpl.get("flavor", True) else ""
    hi, lo = int(tpl.get("text_size", 30)), int(tpl.get("text_min", 16))
    chosen = None
    for with_flavor in ([True, False] if flavor else [False]):
        paras = [(oracle, False)] if oracle else []
        if with_flavor:
            paras.append((flavor, True))
        for s in range(hi, lo - 1, -1):
            lines, th = layout_text(tpl, paras, iw, s)
            if th <= ih:
                chosen = (lines, th, s)
                break
        if chosen:
            break
    if not chosen:
        lines, th = layout_text(tpl, [(oracle, False)], iw, lo)
        chosen = (lines, th, lo)
    lines, th, s = chosen
    draw_lines(img, d, tpl, lines, x + pad, y + pad + max(0, (ih - th) / 2), s, fill, shadow)


# ---------------------------------------------------------------------------------------------------------------------------------------------------------- styles

def _gradient(size: tuple[int, int], c1: str, c2: str, vertical: bool = False) -> Image.Image:
    """c1 -> c2 across the width, or down the height."""
    ramp = Image.linear_gradient("L")                                    # black at the top, white at the bottom
    mask = ramp.resize(size) if vertical else ramp.rotate(90).transpose(Image.FLIP_LEFT_RIGHT).resize(size)
    return Image.composite(Image.new("RGB", size, c2), Image.new("RGB", size, c1), mask)


def _fade(size, a0: int, a1: int) -> Image.Image:
    """An alpha mask fading top to bottom from a0 to a1 (0-255)."""
    return Image.linear_gradient("L").resize(size).point(lambda v: int(a0 + (a1 - a0) * v / 255))


def _placeholder(size: tuple[int, int], th: Theme, label: str, tpl: dict) -> Image.Image:
    im = _gradient(size, th.frame, th.frame2 or th.accent)
    d = ImageDraw.Draw(im, "RGBA")
    d.rectangle((0, 0, size[0], size[1]), fill=(0, 0, 0, 70))
    f, t = fit_line(tpl, label, "title", size[0] * 0.8, 44)
    d.text((size[0] / 2, size[1] / 2), t, font=f, fill=(255, 255, 255, 190), anchor="mm")
    return im


def trim_margins(im: Image.Image) -> Image.Image:
    """Cut off blank white or black margins around a generated picture (the model sometimes draws a narrow panel on a white page), so the art fills the card's window."""
    im = im.convert("RGB")
    w, h = im.size
    g = im.convert("L")
    box = [0, 0, w, h]
    for blank in (lambda v: 255 if v < 236 else 0, lambda v: 255 if v > 20 else 0):          # "has content" masks for white margins and for black margins
        m = g.point(blank)
        cols, rows = list(m.resize((w, 1), Image.BOX).getdata()), list(m.resize((1, h), Image.BOX).getdata())
        def edge(vals, rev=False):
            seq = vals[::-1] if rev else vals
            n = 0
            while n < len(seq) and seq[n] < 0.02 * 255:
                n += 1
            return n
        l, r, t, b = edge(cols), edge(cols, True), edge(rows), edge(rows, True)
        if l + r < w * 0.9 and t + b < h * 0.9 and max(l, r, t, b) >= 0.02 * min(w, h):
            box = [max(box[0], l), max(box[1], t), min(box[2], w - r), min(box[3], h - b)]
    if box == [0, 0, w, h] or box[2] - box[0] < 64 or box[3] - box[1] < 64:
        return im
    return im.crop((box[0] + 2, box[1] + 2, box[2] - 2, box[3] - 2))


def _art(unit, art, th, tpl, size):
    if art is None:
        return _placeholder(size, th, "art pending", tpl)
    return ImageOps.fit(trim_margins(art), size, Image.LANCZOS, centering=(0.5, 0.3))     # crop toward the top: faces live there


def _paste_rounded(img: Image.Image, src: Image.Image, box, radius: int) -> None:
    x, y, w, h = [int(v) for v in box]
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, w - 1, h - 1), radius, fill=255)
    img.paste(src.resize((w, h)), (x, y), mask)


def _rr(d, box, radius, fill=None, outline=None, width=2):
    x, y, w, h = box
    d.rounded_rectangle((x, y, x + w, y + h), radius, fill=fill, outline=outline, width=width)


def _plate(img: Image.Image, box, radius: int, top: str, bottom: str, edge: str, hi: bool = True) -> None:
    """A bevelled plate: a soft top-to-bottom gradient, a dark edge and a thin light line just inside it."""
    x, y, w, h = [int(v) for v in box]
    _paste_rounded(img, _gradient((w, h), top, bottom, vertical=True), (x, y, w, h), radius)
    d = ImageDraw.Draw(img, "RGBA")
    d.rounded_rectangle((x, y, x + w, y + h), radius, outline=edge, width=3)
    if hi:
        d.rounded_rectangle((x + 3, y + 3, x + w - 3, y + h - 3), max(2, radius - 3), outline=(255, 255, 255, 95), width=1)


def style_classic(img, unit, art, tpl, th):
    d = ImageDraw.Draw(img, "RGBA")
    dark = mix(th.frame, "#000000", 0.62)
    fx, fy, fw, fh = tpl.get("frame_box", [30, 30, 690, 968])
    body = _gradient((fw, fh), mix(th.frame, "#ffffff", 0.10), mix(th.frame, "#000000", 0.14), vertical=True)
    if th.frame2:
        side = _gradient((fw, fh), th.frame, th.frame2)
        body = Image.blend(body, side, 0.8)
    _paste_rounded(img, body, (fx, fy, fw, fh), 26)
    d.rounded_rectangle((fx, fy, fx + fw, fy + fh), 26, outline="#050505", width=4)
    d.rounded_rectangle((fx + 5, fy + 5, fx + fw - 5, fy + fh - 5), 22, outline=(255, 255, 255, 70), width=2)
    # the picture, with the frame colour showing as a thin border around it
    ax, ay, aw, ah = [int(v) for v in tpl["art_box"]]
    d.rectangle((ax - 6, ay - 6, ax + aw + 6, ay + ah + 6), fill=mix(th.frame, "#000000", 0.45))
    d.rectangle((ax - 3, ay - 3, ax + aw + 3, ay + ah + 3), fill="#0a0a0a")
    img.paste(_art(unit, art, th, tpl, (aw, ah)), (ax, ay))
    d.rectangle((ax - 1, ay - 1, ax + aw, ay + ah), outline=(255, 255, 255, 60), width=1)
    for key in ("name_box", "type_box"):
        _plate(img, tpl[key], 16, mix(th.plate, "#ffffff", 0.35), mix(th.plate, th.frame, 0.28), dark)
    bx, by, bw, bh = tpl["text_box"]
    _paste_rounded(img, _gradient((bw, bh), th.box, mix(th.box, th.frame, 0.12), vertical=True), (bx, by, bw, bh), 6)
    d.rounded_rectangle((bx, by, bx + bw, by + bh), 6, outline=dark, width=3)
    d.rounded_rectangle((bx + 5, by + 5, bx + bw - 5, by + bh - 5), 3, outline=(0, 0, 0, 35), width=1)
    if _has_pt(unit):
        _plate(img, tpl["pt_box"], 12, mix(th.plate, "#ffffff", 0.3), mix(th.plate, th.frame, 0.35), "#050505")


def style_fullart(img, unit, art, tpl, th):
    img.paste(_art(unit, art, th, tpl, (W, H)), (0, 0))
    black = Image.new("RGB", (W, 190), (6, 6, 8))
    img.paste(black, (0, 0), _fade((W, 190), 210, 0))
    img.paste(Image.new("RGB", (W, 110), (6, 6, 8)), (0, H - 110), _fade((W, 110), 0, 235))      # the small print at the foot needs a dark ground too
    d = ImageDraw.Draw(img, "RGBA")
    _rr(d, tpl["type_box"], 12, fill=(8, 8, 10, 205), outline=th.accent, width=2)
    _rr(d, tpl["text_box"], 12, fill=(8, 8, 10, 175), outline=th.accent, width=2)
    if _has_pt(unit):
        _rr(d, tpl["pt_box"], 14, fill=(8, 8, 10, 235), outline=th.accent, width=4)
    d.rounded_rectangle((4, 4, W - 5, H - 5), 40, outline=th.frame, width=8)


def style_noir(img, unit, art, tpl, th):
    d = ImageDraw.Draw(img, "RGBA")
    d.rectangle((0, 0, W, H), fill="#101114")
    ax, ay, aw, ah = [int(v) for v in tpl["art_box"]]
    _paste_rounded(img, _art(unit, art, th, tpl, (aw, ah)), (ax, ay, aw, ah), 22)
    d.rounded_rectangle((ax, ay, ax + aw, ay + ah), 22, outline=th.accent, width=3)
    d.rounded_rectangle((10, 10, W - 11, H - 11), 34, outline=th.frame, width=4)
    _, ty, _, th_ = tpl["type_box"]
    d.line((tpl["type_box"][0], ty + th_ + 2, tpl["type_box"][0] + tpl["type_box"][2], ty + th_ + 2), fill=th.accent, width=2)
    if _has_pt(unit):
        x, y, w, h = tpl["pt_box"]
        d.rounded_rectangle((x, y, x + w, y + h), 18, fill="#1b1d22", outline=th.accent, width=3)


def _tint_panel(img: Image.Image, box, radius: int, c1: str, c2: str | None, alpha: int, outline: str) -> None:
    """A semi-transparent rounded panel tinted with the card's colour (fading c1 -> c2 for a two-colour card), over whatever is already on the card."""
    x, y, w, h = [int(v) for v in box]
    base = _gradient((w, h), c1, c2 or c1)
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).rounded_rectangle((0, 0, w - 1, h - 1), radius, fill=alpha)
    img.paste(base, (x, y), mask)
    ImageDraw.Draw(img, "RGBA").rounded_rectangle((x, y, x + w, y + h), radius, outline=outline, width=2)


def style_topframe(img, unit, art, tpl, th):
    """Full-bleed picture inside a black border, with a header tinted in the card's colour and translucent dark type and rules panels over it."""
    d = ImageDraw.Draw(img, "RGBA")
    ax, ay, aw, ah = [int(v) for v in tpl["art_box"]]
    _paste_rounded(img, _art(unit, art, th, tpl, (aw, ah)), (ax, ay, aw, ah), 26)
    d.rounded_rectangle((ax, ay, ax + aw, ay + ah), 26, outline="#050505", width=4)
    d.rounded_rectangle((ax + 5, ay + 5, ax + aw - 5, ay + ah - 5), 22, outline=(255, 255, 255, 50), width=2)
    dark = "#0a0a0d"
    _tint_panel(img, tpl["name_box"], 12, mix(dark, th.frame, 0.5), mix(dark, th.frame2, 0.5) if th.frame2 else None, 195, th.accent)
    _rr(d, tpl["type_box"], 12, fill=(8, 8, 10, 175), outline=th.accent, width=2)
    _rr(d, tpl["text_box"], 10, fill=(8, 8, 10, 175), outline=th.accent, width=2)
    if _has_pt(unit):
        _rr(d, tpl["pt_box"], 12, fill=(8, 8, 10, 175), outline=th.accent, width=2)


STYLES = {"classic": style_classic, "fullart": style_fullart, "noir": style_noir, "topframe": style_topframe}


def _has_pt(unit: dict) -> bool:
    return bool(unit.get("power") is not None and unit.get("toughness") is not None) or bool(unit.get("loyalty") or unit.get("defense"))


# ---------------------------------------------------------------------------------------------------------------------------------------------------------- the card

def render(unit: dict, art: Image.Image | None, tpl: dict, *, scale: float = 1.0, footer: bool = True, footer_text: str | None = None) -> Image.Image:
    """The finished card as an RGB picture, 750x1050 times `scale`."""
    th = theme_for(unit)
    img = Image.new("RGB", (W, H), "#0b0b0b")
    STYLES[tpl.get("style", "classic")](img, unit, art, tpl, th)
    d = ImageDraw.Draw(img, "RGBA")
    ink = tpl.get("ink", "#141414")
    body_ink = tpl.get("body_ink", ink)
    shadow = bool(tpl.get("shadow", False))
    pad = tpl.get("plate_pad", 18)

    # name and mana cost on the name plate
    nx, ny, nw, nh = tpl["name_box"]
    dia = min(nh * 0.56, 34)
    cost_left = draw_cost(img, tpl, unit.get("mana_cost", ""), nx + nw - pad + 2, ny + (nh - dia) / 2, dia) if unit.get("mana_cost") else nx + nw - pad
    f, name = fit_line(tpl, unit.get("name", ""), "title", cost_left - (nx + pad) - 10, tpl.get("name_size", 38), 18)
    if tpl.get("name_shadow", shadow):
        d.text((nx + pad + 1.5, ny + nh / 2 + 2), name, font=f, fill=(0, 0, 0, 210), anchor="lm")
    d.text((nx + pad, ny + nh / 2 + 1), name, font=f, fill=tpl.get("name_ink", ink), anchor="lm")

    # type line
    tx, ty, tw, tbh = tpl["type_box"]
    f, tl = fit_line(tpl, unit.get("type_line", ""), "title", tw - 2 * pad, tpl.get("type_size", 32), 16)
    if shadow:
        d.text((tx + pad + 1.5, ty + tbh / 2 + 2), tl, font=f, fill=(0, 0, 0, 210), anchor="lm")
    d.text((tx + pad, ty + tbh / 2 + 1), tl, font=f, fill=tpl.get("type_ink", ink), anchor="lm")

    draw_body(img, d, tpl, unit, body_ink, tpl.get("body_shadow", shadow and tpl.get("style") == "fullart"))

    if _has_pt(unit):
        px, py, pw, ph = tpl["pt_box"]
        txt = f"{unit['power']}/{unit['toughness']}" if unit.get("power") is not None else str(unit.get("loyalty") or unit.get("defense"))
        f, txt = fit_line(tpl, txt, "title", pw - 16, tpl.get("pt_size", 42), 20)
        d.text((px + pw / 2, py + ph / 2 + 1), txt, font=f, fill=tpl.get("pt_ink", ink), anchor="mm")

    if footer:
        fx, fy = tpl.get("footer_xy", [W / 2, H - 16])
        d.text((fx, fy), footer_text or FOOTER, font=font(tpl, "body", 15), fill=tpl.get("footer_ink", "#bdbdbd"), anchor="mm")
    if scale != 1.0:
        img = img.resize((int(W * scale), int(H * scale)), Image.LANCZOS)
    return img


