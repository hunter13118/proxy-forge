"""
Drawing a proxy card: a template (JSON geometry + a drawing style) + a card unit + the art -> a 750x1050 picture (2.5 x 3.5 in at 300 dpi).

Templates live in proxy_forge/templates/<id>.json (and in <data>/templates for your own). A template says where the art window, the name, the type line, the rules text and the
power/toughness go (coordinates in the 750x1050 card), which fonts and colours to use, and which `style` draws the frame around them: "classic" (the modern coloured frame with
bevelled plates), "fullart" (the art fills the card, translucent panels), "topframe" (the coloured frame and name plate on top, full-bleed art below) or "noir" (dark card, art window on top). A new look that only moves boxes and changes colours is a new
JSON file. The art is separate from the template, so changing the template re-draws the cards without drawing any art again.

Fonts: the project's own `fonts/` folder first, then Windows'. Mana and other symbols come from the Mana icon font (fonts/mana.ttf, mana-glyphs.json), drawn as discs the way Magic
prints them. If you own fonts you want to use (Beleren, MPlantin), drop them in `fonts/` as beleren.ttf / mplantin.ttf (and mplantin-italic.ttf) and they are picked up first.
"""
